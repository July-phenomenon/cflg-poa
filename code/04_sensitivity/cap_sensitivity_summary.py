# -*- coding: utf-8 -*-
"""Post-processing for the cap/coverage-floor sensitivity sweep (Appendix C).

Reads the three per-config grids produced by cap_floor_sensitivity.py
(theta in {0.50, 0.60, 0.70}) and the published full-enumeration archive, then
emits:

  1. a human-readable summary  -> results/sensitivity/cap_floor_summary.md
  2. a LaTeX table fragment    -> results/sensitivity/cap_floor_appendixC.tex

Checks performed per grid
-------------------------
* Theorem 1 (coverage-locked layer): for every config with
  |milp_F1 - nash_F1| <= 1e-9, PoA must be <= 1/theta.  Violations must be 0.
* Corollary 1 (c_N >= c_min subset, c_min in {0.7, 0.8, 0.9}): for every
  config whose Nash coverage clears the floor, PoA must be <= 1/(theta*c_min).
  Violations must be 0; the subset size itself is reported (it is the
  empirical footprint of the floor, cf. paper Section 4 roadmap).
* theta = 0.6 grid additionally cross-checks its aggregate statistics against
  the published archive (distribution-level reproduction; per-config identity
  is NOT expected -- known geometry-calibration caveat).
"""
from __future__ import annotations

import json
import os
import sys

import numpy as np

_HERE = os.path.dirname(os.path.abspath(__file__))
_SOLVER = os.path.abspath(os.path.join(_HERE, "..", "02_core_solver"))
_UTILS = os.path.abspath(os.path.join(_HERE, "..", "utils"))
for _p in (_SOLVER, _UTILS):
    if _p not in sys.path:
        sys.path.insert(0, _p)

import constants                      # noqa: E402

GRID_DIR = os.path.join(constants.PKG_ROOT, "results", "sensitivity")
ARCHIVE = os.path.abspath(os.path.join(
    constants.PKG_ROOT, "..", "..", "原始实验结果存档", "全量枚举",
    "poa_full_per_config_s2.json"))
THETAS = [0.50, 0.60, 0.70]
C_MINS = [0.70, 0.80, 0.90]
TOL_LOCK = 1e-9


def load_grid(theta):
    path = os.path.join(GRID_DIR, "cap_floor_theta_%.2f_per_config.json" % theta)
    with open(path, encoding="utf-8") as f:
        recs = json.load(f)["results"]
    recs = [r for r in recs if r["nash_F2"] > 0]
    return recs


def stats(recs):
    poa = np.array([r["PoA"] for r in recs])
    return dict(n=len(recs), mean=poa.mean(), median=float(np.median(poa)),
                p95=float(np.percentile(poa, 95)), max=poa.max())


def main():
    lines = ["# Cap / coverage-floor sensitivity summary",
             "", "Generated by cap_sensitivity_summary.py.", ""]
    tex = [
        "\\begin{table}[pos=!htbp]",
        "\\small\\centering",
        "\\caption{Sensitivity of the PoA to the satisfaction cap $\\theta$",
        " (full enumeration, $n=15{,}207$ per grid). Theorem~\\ref{thm:universal}",
        " predicts the bound $1/\\theta$ for coverage-locked configurations;",
        " no violation is observed in any grid. Corollary~\\ref{cor:relaxed}'s",
        " subset is the configurations whose decentralized coverage clears the",
        " floor $c_{\\min}$; its bound is $1/(\\theta c_{\\min})$.}",
        "\\label{tab:sensitivity}",
        "\\begin{tabular}{lrrrrrr}",
        "\\toprule",
        "$\\theta$ & $1/\\theta$ & Locked $n$ & Max PoA$_{\\mathrm{locked}}$ &",
        " Mean & P95 & Max \\\\",
        "\\midrule",
    ]

    grids = {}
    for theta in THETAS:
        recs = load_grid(theta)
        grids[theta] = recs
        s = stats(recs)
        locked = [r for r in recs if abs(r["milp_F1"] - r["nash_F1"]) < TOL_LOCK]
        sl = stats(locked)
        bound = 1.0 / theta
        viol = sum(1 for r in locked if r["PoA"] > bound + 1e-9)
        lines += [
            "## theta = %.2f" % theta,
            "- all:      n=%d mean=%.4f median=%.4f p95=%.4f max=%.4f"
            % (s["n"], s["mean"], s["median"], s["p95"], s["max"]),
            "- locked:   n=%d mean=%.4f max=%.4f  | theorem-1 bound 1/theta=%.4f"
            "  violations=%d" % (len(locked), sl["mean"], sl["max"], bound, viol),
        ]
        assert viol == 0, "Theorem 1 VIOLATED at theta=%.2f (%d configs)" % (theta, viol)
        tex.append("%.2f & %.3f & %d & %.4f & %.4f & %.4f & %.4f \\\\"
                   % (theta, bound, len(locked), sl["max"],
                      s["mean"], s["p95"], s["max"]))
        # Corollary-1 subsets
        for cmin in C_MINS:
            sub = [r for r in recs if r["nash_F1"] >= cmin - 1e-12]
            if not sub:
                lines.append("  - corollary c_min=%.1f: EMPTY subset" % cmin)
                continue
            ss = stats(sub)
            cb = 1.0 / (theta * cmin)
            cv = sum(1 for r in sub if r["PoA"] > cb + 1e-9)
            lines.append("  - corollary c_min=%.1f: n=%d max=%.4f bound=%.4f"
                         " violations=%d" % (cmin, len(sub), ss["max"], cb, cv))
            assert cv == 0, ("Corollary 1 VIOLATED at theta=%.2f c_min=%.2f"
                             % (theta, cmin))
        lines.append("")

    tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]

    # Reproduction cross-check (theta = 0.6 vs published archive)
    if os.path.exists(ARCHIVE):
        with open(ARCHIVE, encoding="utf-8") as f:
            arch = [c for c in json.load(f)["results"] if c["nash_F2"] > 0]
        apoa = np.array([c["milp_F2"] / c["nash_F2"] for c in arch])
        ref = dict(n=len(arch), mean=apoa.mean(), p95=float(np.percentile(apoa, 95)),
                   max=apoa.max())
        s6 = stats(grids[0.60])
        lines += [
            "## Reproduction cross-check (theta=0.6 vs published archive)",
            "- archive : n=%d mean=%.4f p95=%.4f max=%.4f"
            % (ref["n"], ref["mean"], ref["p95"], ref["max"]),
            "- this run: n=%d mean=%.4f p95=%.4f max=%.4f"
            % (s6["n"], s6["mean"], s6["p95"], s6["max"]),
            "- NOTE: per-config identity is NOT expected (geometry-calibration",
            "  caveat); agreement at distribution level is the pass criterion.",
            "",
        ]

    with open(os.path.join(GRID_DIR, "cap_floor_summary.md"), "w",
              encoding="utf-8") as f:
        f.write("\n".join(lines))
    with open(os.path.join(GRID_DIR, "cap_floor_appendixC.tex"), "w",
              encoding="utf-8") as f:
        f.write("\n".join(tex))
    print("\n".join(lines))
    print("LaTeX fragment ->", os.path.join(GRID_DIR, "cap_floor_appendixC.tex"))


if __name__ == "__main__":
    main()
