# -*- coding: utf-8 -*-
"""Summarise the satisfaction-ladder refinement sweep (paper P2-1).

Reads every ``results/sensitivity/ladder_K<K>_per_config.json`` produced by
``ladder_refinement.py`` and reports, for each ladder granularity K:

  * full-enumeration statistics of the measured ratio (mean / median / p95 /
    min / max / tie rate);
  * the same statistics restricted to the LOCKED layer, i.e. the
    configurations in which the two allocations serve the same population
    share (|milp_F1 - nash_F1| < 1e-12).  Proposition 1's bound of
    1/0.60 = 1.667 applies only there, so this is the layer in which the
    bound is falsifiable;
  * the maximum locked-layer ratio against that bound.

The scientific question is whether the small measured PoA is an artefact of
the coarse five-level satisfaction ladder.  The diagnostics that discriminate
are: (i) does the mean move when the ladder is refined?  (ii) does the tie
rate collapse?  (iii) does the locked-layer maximum stay under 1.667?

Usage
-----
    python ladder_summary.py
    python ladder_summary.py --tex results/sensitivity/ladder_summary.tex
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import statistics as st

_HERE = os.path.dirname(os.path.abspath(__file__))
_RES = os.path.abspath(os.path.join(_HERE, "..", "..", "results", "sensitivity"))
BOUND = 1.0 / 0.60          # Proposition 1, valid on the locked layer
TIE = 1e-12


def _q(v, p):
    s = sorted(v)
    return s[min(len(s) - 1, max(0, int(p * len(s))))]


def _stats(p):
    if not p:
        return None
    return dict(n=len(p), mean=st.mean(p), median=st.median(p),
                p95=_q(p, 0.95), p99=_q(p, 0.99), min=min(p), max=max(p),
                tie=sum(1 for x in p if abs(x - 1.0) < TIE) / len(p))


def load_all():
    arms = []
    for f in sorted(glob.glob(os.path.join(_RES, "ladder_K*_per_config.json"))):
        d = json.load(open(f, encoding="utf-8"))
        if d.get("parameters", {}).get("limit"):
            continue                      # skip smoke-test runs
        arms.append(d)
    arms.sort(key=lambda d: d["K"])
    return arms


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tex", default=None, help="also write a LaTeX table here")
    args = ap.parse_args()

    arms = load_all()
    if not arms:
        print("no ladder arms found in %s" % _RES)
        return

    print("Satisfaction-ladder refinement (15,207 configurations per arm)")
    print("Proposition 1 bound = %.4f, valid on the locked layer only\n" % BOUND)

    hdr = ("%5s %6s | %7s %7s %7s %7s %7s %7s | %7s %7s %7s %7s"
           % ("K", "n", "mean", "median", "p95", "max", "min", "tie",
              "lock_n", "lock_mean", "lock_p99", "lock_max"))
    print(hdr)
    print("-" * len(hdr))

    rows = []
    for d in arms:
        r = [x for x in d["results"] if x and x.get("PoA") is not None]
        p = [x["PoA"] for x in r]
        lock = [x["PoA"] for x in r
                if abs(x["milp_F1"] - x["nash_F1"]) < TIE]
        s, sl = _stats(p), _stats(lock)
        if s is None:
            continue
        print("%5d %6d | %7.4f %7.4f %7.4f %7.4f %7.4f %7.4f | %7d %9.4f %8.4f %8.4f"
              % (d["K"], s["n"], s["mean"], s["median"], s["p95"], s["max"],
                 s["min"], s["tie"], sl["n"], sl["mean"], sl["p99"], sl["max"]))
        rows.append((d["K"], s, sl, d.get("elapsed_s")))

    base = rows[0]
    print("\nChange relative to the published ladder (K=%d):" % base[0])
    for K, s, sl, _ in rows[1:]:
        print("  K=%-4d  mean %+0.4f  median %+0.4f  tie %+0.4f  "
              "lock_mean %+0.4f  lock_max %+0.4f"
              % (K, s["mean"] - base[1]["mean"],
                 s["median"] - base[1]["median"],
                 s["tie"] - base[1]["tie"],
                 sl["mean"] - base[2]["mean"], sl["max"] - base[2]["max"]))

    print("\nBound check on the locked layer (Proposition 1 = %.4f):" % BOUND)
    for K, s, sl, _ in rows:
        flag = "OK" if sl["max"] <= BOUND + 1e-9 else "EXCEEDS"
        print("  K=%-4d  lock_max = %.4f   -> %s" % (K, sl["max"], flag))

    if args.tex:
        with open(args.tex, "w", encoding="utf-8") as f:
            f.write("%% auto-generated by ladder_summary.py\n")
            f.write("\\begin{tabular}{rrrrrrrr}\\hline\n")
            f.write("K & $n$ & mean & median & $p_{95}$ & max & tie & "
                    "locked max \\\\\\hline\n")
            for K, s, sl, _ in rows:
                f.write("%d & %d & %.4f & %.4f & %.4f & %.4f & %.3f & %.4f \\\\\n"
                        % (K, s["n"], s["mean"], s["median"], s["p95"], s["max"],
                           s["tie"], sl["max"]))
            f.write("\\hline\\end{tabular}\n")
        print("\nwrote %s" % args.tex)


if __name__ == "__main__":
    main()
